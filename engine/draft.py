"""P1 agent-draft: same-language output (the rebuild is ALWAYS the original's language).

Policy: we never translate to a "nicer" language here. The detected language
(config/toolchain.yaml, written by tools/provenance.py) is the output language:
  * pascal -> per-function src/<fn>.inc Pascal skeletons + a src/<slug>.pas program
              that {$INCLUDE}s them; Ghidra's decompiled C is kept as a reference
              comment and (with --llm) translated C->Pascal via same-toolchain few-shot.
  * c      -> per-function src/<fn>.c (for genuinely-C targets).
A future project may port the verified same-language source to modern languages;
that is explicitly out of scope for this factory.

Gate: a target is NOT drafted until its language is known with confidence (>=medium
for pascal/c). Unknown/ambiguous language -> SKIP (do not emit the wrong language).

Disc-gated: SKIP without asm/. Hit-rate monitored by engine/scheduler.py.
"""
from __future__ import annotations
import argparse, pathlib, re, shutil, subprocess, sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import knowledge  # noqa: E402

C_TEMPLATE = """/* {slug}::{fn} — {kind} candidate (oracle: {oracle}).
 * Drafted from asm/{fn}.s via {backend}; UNMATCHED until verify passes.
 * Original assembly retained in asm/{fn}.s (INCLUDE_ASM residue).
 */
{body}
"""

PAS_TEMPLATE = """{{ {slug}::{fn} — {kind} Pascal draft (oracle: {oracle}).
  Drafted from asm/{fn}.s via {backend}; UNMATCHED until verify passes.
  Original assembly retained in asm/{fn}.s (INCLUDE_ASM residue).
  Reference: Ghidra decompiler C for this function is embedded below as a comment.
}}
{ref}
{sig}
"""

PAS_PROGRAM = """{{ {slug} — playable-parity rebuild (Turbo Pascal 7 / Free Pascal -Mtp proxy).
  Same language as the original. Auto-generated by engine/draft.py; each function
  is an INCLUDE_ASM-residue draft until an oracle verifies it. Do not hand-edit
  without re-running draft; unmatched bodies live in asm/.
}}
{{$MODE TP}}
{{$ASMMODE INTEL}}
program {prog};
{{$INCLUDE _forward.inc}}
{includes}
begin
  {{ entry stub: original main/game loop not yet matched }}
end.
"""

FALLBACK_BODY = "int {fn}(void) {{\n    return 0; /* TODO: match original semantics */\n}}\n"

LANG_EXT = {"pascal": ".inc", "c": ".c"}
KNOWN_LANGS = set(LANG_EXT)


def _yaml_kv(path: pathlib.Path, key: str, default: str = "unknown") -> str:
    if not path.exists():
        return default
    for line in path.read_text().splitlines():
        if line.startswith(key + ":"):
            return line.split(":", 1)[1].strip() or default
    return default


def read_recon_seed(recon_dir: pathlib.Path, fn: str,
                    allowed: set[str] | None = None) -> tuple[str | None, str]:
    """Judge-verified C for fn from a recon corpus (None, reason if unusable).

    Parses the provenance header written by the night-3 G4 phase
    ('Dual-judge: qwen=<s> phi=<s> verdict=<v>') and only accepts verdicts
    in `allowed` (default {'real'}). Returns (code, verdict-or-reason).
    """
    if allowed is None:
        allowed = {"real"}
    p = recon_dir / f"{fn}.c"
    if not p.exists():
        return None, "no-recon-file"
    text = p.read_text(errors="replace")
    m = re.search(r"Dual-judge: qwen=(\S+) phi=(\S+) verdict=(\S+)", text)
    verdict = m.group(3) if m else "unparsed"
    if verdict not in allowed:
        return None, f"verdict-{verdict}"
    lines = text.splitlines()
    body = "\n".join(ln for ln in lines
                     if not ln.startswith(("/*", " *", " */")))
    code = body.strip() or None
    return code, verdict


def detect_language(target: str) -> tuple[str, str, str]:
    """(language, compiler_confidence, compiler) from toolchain.yaml then target.yaml."""
    cfg = pathlib.Path(f"targets/{target}/config")
    tc = cfg / "toolchain.yaml"
    ty = cfg / "target.yaml"
    language = _yaml_kv(tc, "language", _yaml_kv(ty, "language", "unknown")).lower()
    conf = _yaml_kv(tc, "compiler_confidence", _yaml_kv(ty, "compiler_confidence", "low"))
    compiler = _yaml_kv(tc, "compiler", _yaml_kv(ty, "compiler", "unknown"))
    return language, conf, compiler


def read_decomp_seed(root: pathlib.Path, fn: str) -> str | None:
    p = root / "decomp" / f"{fn}.c"
    if p.exists() and p.stat().st_size > 0:
        return p.read_text(errors="replace")
    return None


def _pas_ident(name: str) -> str:
    keep = "_.abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
    s = "".join(c if c in keep else "_" for c in name) or "unnamed"
    return s if s[0].isalpha() else "fn_" + s


def _c_ref_block(c_text: str, source: str = "Ghidra") -> str:
    """Embed decompiler C as Pascal line comments (//) — C can't contain a closer.

    A Pascal block comment (* *) would be terminated early by C pointer syntax
    like `*)`, so every reference line is prefixed with // instead.
    """
    lines = [f"// --- reference: {source} decompiler C (unmatched) ---"]
    lines += ["// " + ln for ln in c_text.splitlines()]
    lines.append("// --- end reference ---")
    return "\n".join(lines)


def _pascal_fn_skeleton(fn: str) -> str:
    """A compilable Pascal procedure stub (safe default; oracle enforces semantics)."""
    return (f"procedure {_pas_ident(fn)};\n"
            f"begin\n"
            f"  {{ TODO: translate from asm/{fn}.s — UNMATCHED until an oracle passes }}\n"
            f"end;\n")


def _sanitize_pascal(text: str) -> str:
    """Strip markdown fences / prose so the LLM output is bare, compilable Pascal.

    Models often wrap code in ```pascal ... ``` or prepend a sentence ("This Pascal
    code..."). Both break compilation when INCLUDEd. We keep the fenced code if
    present, then REQUIRE a real routine declaration line (`procedure|function Name`)
    plus a `begin`; otherwise return "" so the caller falls back to a skeleton.
    """
    if not text:
        return ""
    t = text.strip()
    if "```" in t:  # keep the largest fenced chunk (the code)
        chunks = [p for p in t.split("```") if p.strip()]
        code = max(chunks, key=len)
        code = "\n".join(ln for ln in code.splitlines()
                         if ln.strip().lower() not in ("pascal", "delphi", "pas", "cpp", "c"))
        t = code.strip()
    # drop any leading prose: keep from the first real routine-declaration line
    lines = t.splitlines()
    start = 0
    for i, ln in enumerate(lines):
        if re.match(r"\s*(procedure|function)\s+[A-Za-z_]\w*", ln, re.I):
            start = i
            break
    t = "\n".join(lines[start:]).strip()
    # strip any `...; forward;` declarations the model emits: _forward.inc
    # already declares every sibling routine, so re-declaring them is an error.
    t = re.sub(r"(?im)^\s*(procedure|function)\s+[A-Za-z_]\w*(\s*\([^;]*\))?\s*;\s*forward\s*;\s*$",
               "", t).strip()
    # strict: must contain an actual routine declaration and a begin
    has_decl = re.search(r"^\s*(procedure|function)\s+[A-Za-z_]\w*", t, re.M | re.I)
    if not has_decl or "begin" not in t.lower():
        return ""
    # TP7-validity gate: reject output that still carries Ghidra/C residue the
    # model failed to translate into real Pascal. These are undeclared globals
    # (DAT_), register/param noise (unaff_, in_, out_, AX..DI), non-TP7 syntax
    # (0x hex, C pointer deref, ->), or C types. Better to fall back to a
    # compiling skeleton than ship a .inc that breaks the whole-program build.
    if re.search(r"\bDAT_\w+|\bPCode\b|\bPop\b|"
                 r"\b(unaff|in|out)_[A-Za-z]\w*|\b(AX|BX|CX|DX|SI|DI|SP|BP|ES|DS|CS|SS)\b"
                 r"|\b0x[0-9a-fA-F]+\b|\*\(|->|\b(uint|ushort|uchar|int|short|long|float|double|undefined)\d*\b", t):
        return ""
    return t


def fewshot_context(target: str, compiler: str, platform: str) -> str:
    """Prompt prefix of same-toolchain few-shot examples (asm -> decompiled C)."""
    data = knowledge.load()
    exs = knowledge.examples_for(data, compiler, platform, limit=3,
                                 min_confidence="medium")
    priors = knowledge.prior_targets_with(data, compiler, platform)
    if not exs:
        return ""
    parts = [f"Prior reference translations for {compiler}/{platform} "
             f"(learned from: {', '.join(priors) or 'this toolchain'}):"]
    for e in exs:
        parts.append(f"--- {e['fn']} ({e.get('calling_convention','?')}) ---")
        parts.append("ASM:\n" + e["asm_head"])
        parts.append("C:\n" + e["c"][:1200])
    return "\n".join(parts) + "\n\n"


def run_m2c(asm_file: pathlib.Path, target_yaml: pathlib.Path) -> str | None:
    m2c = shutil.which("m2c")
    if not m2c:
        return None
    try:
        r = subprocess.run([m2c, str(asm_file)], capture_output=True, text=True, timeout=60)
        if r.returncode == 0 and r.stdout.strip():
            return r.stdout
    except Exception as e:
        print(f"[m2c] {e}")
    return None


def run_llm(prompt: str, model: str | None, endpoint: str | None) -> str | None:
    """Local-first: llama.cpp server (/completion) or `llm` CLI; hosted only if LSR_ALLOW_HOSTED=1."""
    import json, os, urllib.request
    if endpoint:
        try:
            data = json.dumps({"prompt": prompt, "n_predict": 768}).encode()
            req = urllib.request.Request(endpoint.rstrip("/") + "/completion", data=data,
                                         headers={"Content-Type": "application/json"})
            with urllib.request.urlopen(req, timeout=300) as resp:
                return json.loads(resp.read()).get("content")
        except Exception as e:
            print(f"[llm-endpoint] {e}")
            return None
    cli = shutil.which("llm")
    if cli and model:
        try:
            r = subprocess.run([cli, "-m", model, prompt], capture_output=True, text=True, timeout=300)
            if r.returncode == 0 and r.stdout.strip():
                return r.stdout
        except Exception as e:
            print(f"[llm-cli] {e}")
    if os.environ.get("LSR_ALLOW_HOSTED") != "1":
        return None
    return None


def _write_program(root: pathlib.Path, slug: str, fns: list[str]) -> None:
    """(Re)generate the Pascal program + a forward-declaration header.

    The header forward-declares every routine so cross-function calls in the
    per-function .inc bodies resolve (incremental-decomp pattern), then the
    program includes each body. {$ASMMODE INTEL} lets translated inline-asm
    (TP7 `asm...end;`) assemble under the FPC proxy.
    """
    prog = "".join(ch for ch in slug if ch.isalnum() or ch == "_") or "game"
    fwd = "\n".join(f"procedure {_pas_ident(f)}; forward;" for f in fns)
    (root / "src" / "_forward.inc").write_text(
        "{ forward declarations for every routine (generated) }\n" + fwd + "\n")
    incs = "\n".join(f"{{$INCLUDE {f}.inc}}" for f in fns)
    (root / "src" / f"{slug}.pas").write_text(
        PAS_PROGRAM.format(slug=slug, prog=prog, includes=incs))


def _compile_gate(root: pathlib.Path, target: str) -> int:
    """Revert any .inc that breaks the FPC whole-program build to a skeleton.

    The LLM sometimes emits Pascal that passes the token gate but still fails
    FPC (type mismatches, illegal qualifiers, duplicate declares). Rather than
    ship a broken build, run `make build`, parse which src/<fn>.inc files errored,
    overwrite those with compiling skeletons, and rebuild. Returns the number of
    functions reverted.
    """
    src = root / "src"

    def _errors() -> set[str]:
        r = subprocess.run(["make", "build"], cwd=root, capture_output=True,
                           text=True, timeout=300)
        out = r.stdout + r.stderr
        return set(re.findall(r"([A-Za-z_]\w*)\.inc\(\d+,\d+\)\s+(?:Error|Fatal)", out))

    bad = _errors()
    if not bad:
        return 0
    reverted = 0
    for stem in sorted(bad):
        p = src / f"{stem}.inc"
        if not p.exists():
            continue
        seed = read_decomp_seed(root, stem)
        ref = _c_ref_block(seed) if seed else "(* no decompiler seed yet *)"
        p.write_text(PAS_TEMPLATE.format(
            slug=target, fn=stem,
            kind=_yaml_kv(root / "config" / "target.yaml", "kind", "game"),
            oracle="none", backend="skeleton(compile-gate)", ref=ref,
            sig=_pascal_fn_skeleton(stem)))
        reverted += 1
    still = _errors()
    print(f"[draft:{target}] compile-gate reverted {reverted} fn(s) that broke the "
          f"build -> {'GREEN' if not still else 'STILL BROKEN: ' + ','.join(sorted(still))}")
    return reverted


def draft(target: str, fn: str | None = None, oracle: str = "none",
          use_llm: bool = False, model: str | None = None,
          endpoint: str | None = None, limit: int | None = None,
          recon_dir: str | None = None,
          recon_verdicts: str = "real") -> int:
    root = pathlib.Path("targets") / target
    asm = root / "asm"
    if not asm.exists() or not any(asm.glob("*.s")):
        print(f"[draft:{target}] SKIP no asm/ (run ingest with BYOD first)")
        return 0
    recon = pathlib.Path(recon_dir) if recon_dir else None
    allowed = {v.strip() for v in recon_verdicts.split(",") if v.strip()}
    n_recon = 0

    language, conf, compiler = detect_language(target)
    if language not in KNOWN_LANGS:
        print(f"[draft:{target}] SKIP language not detected (language={language!r}); "
              f"run provenance to establish the toolchain before drafting")
        return 0
    if not knowledge.confidence_ok({"compiler_confidence": conf}, "medium"):
        print(f"[draft:{target}] SKIP low toolchain confidence ({conf}); "
              f"refusing to emit {language} from an unconfirmed detection")
        return 0

    (root / "src").mkdir(parents=True, exist_ok=True)
    kind = _yaml_kv(root / "config" / "target.yaml", "kind", "game")
    platform = _yaml_kv(root / "config" / "target.yaml", "platform",
                        _yaml_kv(root / "config" / "toolchain.yaml", "platform", "unknown"))
    ext = LANG_EXT[language]
    fns = [fn] if fn else [p.stem for p in sorted(asm.glob("*.s"))]
    # `batch` = the subset to actively LLM-translate this run (None = all).
    # Every function in `fns` still gets an .inc + forward-declaration so that
    # cross-routine calls resolve; non-batch functions get a skeleton body.
    batch: set[str] | None = None
    if limit and not fn:
        # validate on the smallest REAL functions first (skip degenerate
        # halt_baddata/bad-instruction stubs Ghidra couldn't decompile)
        def _real(s: str) -> bool:
            c = root / "decomp" / f"{s}.c"
            if not c.exists():
                return True
            t = c.read_text(errors="replace")
            return not re.search(r"halt_baddata|Bad instruction|Truncating control flow", t)
        real = [s for s in fns if _real(s)]
        batch = set(sorted(real, key=lambda s: (asm / f"{s}.s").stat().st_size)[:limit])
    fs_prefix = fewshot_context(target, compiler, platform)

    # prune stale drafts (idempotent re-ingest / language switch)
    src_dir = root / "src"
    want = set(fns)
    for old in list(src_dir.glob("*.c")) + list(src_dir.glob("*.inc")):
        if old.stem not in want:
            old.unlink()

    n_seeded = 0
    for f in fns:
        out = src_dir / f"{f}{ext}"
        if out.exists():
            continue
        seed_c = read_decomp_seed(root, f)
        backend = "skeleton"
        if language == "c":
            body, backend = FALLBACK_BODY.format(fn=f), "template"
            if seed_c:
                body, backend = seed_c, "ghidra-decomp"; n_seeded += 1
            if not seed_c:
                m2c_out = run_m2c(asm / f"{f}.s", root / "config" / "target.yaml")
                if m2c_out:
                    body, backend = m2c_out, "m2c"
            if use_llm:
                llm_out = run_llm(fs_prefix + f"Rewrite to match original {kind} {f}:\n{body}",
                                  model, endpoint)
                if llm_out:
                    body, backend = llm_out, f"ghidra-decomp+llm({model or endpoint})"
            out.write_text(C_TEMPLATE.format(slug=target, fn=f, kind=kind,
                                             oracle=oracle, backend=backend, body=body))
        else:  # pascal
            ref_source = "Ghidra"
            if recon is not None:
                rcode, rwhy = read_recon_seed(recon, f, allowed)
                if rcode:
                    seed_c = rcode
                    ref_source = f"recon:{rwhy}"
                    n_recon += 1
            ref = _c_ref_block(seed_c, ref_source) if seed_c else "(* no decompiler seed yet *)"
            sig = _pascal_fn_skeleton(f)
            backend = "skeleton"
            if seed_c:
                n_seeded += 1
                if use_llm and (batch is None or f in batch):
                    asm_text = (asm / f"{f}.s").read_text(errors="replace")[:3000]
                    prompt = (
                        "You are reconstructing the ORIGINAL Turbo Pascal 7 (16-bit real-mode "
                        "DOS) source of a function. Given the disassembly and a C reference, "
                        "output the Pascal it most likely came from.\n"
                        "RULES:\n"
                        "- Output ONLY Turbo Pascal 7 source: a single `procedure Name;` (or "
                        "`function`) with a `begin ... end;` body. No markdown, no prose, no "
                        "comments except brief ones.\n"
                        "- It must compile standalone under {$MODE TP} with no undeclared "
                        "identifiers. Use only standard TP7 types (Byte, Word, Integer, "
                        "Boolean, Char, Pointer, String).\n"
                        "- The C uses fake identifiers (FUN_xxxx, DAT_xxxx, uVarN) — replace "
                        "them with plain Pascal locals/params; do not invent globals.\n"
                        "- Preserve control flow and arithmetic exactly. If a construct has no "
                        "clean Pascal form (e.g. a far call to another routine), call "
                        "that routine by name; every sibling routine is ALREADY "
                        "forward-declared, so DO NOT declare or define any "
                        "other procedure/function.\n"
                        f"- The routine is named `{f}`; keep that exact name.\n\n"
                        f"ASSEMBLY:\n{asm_text}\n\nREFERENCE C ({ref_source}, for meaning only):\n{seed_c}\n")
                    llm_out = run_llm(prompt, model, endpoint)
                    clean = _sanitize_pascal(llm_out) if llm_out else ""
                    if clean:
                        sig, backend = clean, f"c->pascal+llm({model or endpoint},{ref_source})"
            out.write_text(PAS_TEMPLATE.format(slug=target, fn=f, kind=kind,
                                               oracle=oracle, backend=backend,
                                               ref=ref, sig=sig))
    if language == "pascal":
        _write_program(root, target, fns)
        if use_llm:
            _compile_gate(root, target)
    if fs_prefix:
        print(f"[draft:{target}] few-shot {compiler}/{platform} context applied "
              f"(learned from prior targets)")
    print(f"[draft:{target}] {len(fns)} fns -> src/*{ext} "
          f"({n_seeded} decompiler-seeded, {n_recon} recon-seeded) "
          f"language={language} conf={conf}")
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--target", default=None)
    ap.add_argument("--fn", default=None)
    ap.add_argument("--oracle", default="none")
    ap.add_argument("--llm", action="store_true", help="translate/refine via local LLM")
    ap.add_argument("--model", default=None)
    ap.add_argument("--endpoint", default=None, help="llama.cpp/vLLM server URL")
    ap.add_argument("--limit", type=int, default=None,
                    help="translate only the N smallest functions (validate a batch first)")
    ap.add_argument("--recon-dir", default=None,
                    help="judge-verified recon C corpus dir (seed instead of Ghidra decomp)")
    ap.add_argument("--recon-verdicts", default="real",
                    help="comma-separated verdicts to accept (default: real)")
    a = ap.parse_args()
    sys.exit(draft(a.target, a.fn, a.oracle, a.llm, a.model, a.endpoint, a.limit,
                   a.recon_dir, a.recon_verdicts))
